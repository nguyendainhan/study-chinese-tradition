let fixedHanVietCount = 0;
let fixedExactViCount = 0;

for (const w of words) {
  const newHv = fixHanViet(w);
  if (newHv && newHv !== w.hanViet) {
    w.hanViet = newHv;
    fixedHanVietCount++;
  }

  if (EXACT_VI_BY_ID[w.id]) {
    w.vietnamese = EXACT_VI_BY_ID[w.id];
    fixedExactViCount++;
  } else if (EXACT_VI_BY_TRAD[w.traditional]) {
    w.vietnamese = EXACT_VI_BY_TRAD[w.traditional];
    fixedExactViCount++;
  }
}

// 3. Disambiguate remaining duplicate groups where different Chinese words share the exact same Vietnamese string
const byVi = {};
for (const w of words) {
  const v = (w.vietnamese || '').trim().toLowerCase();
  if (!v) continue;
  if (!byVi[v]) byVi[v] = [];
  byVi[v].push(w);
}

let disambiguatedCount = 0;
for (const [viLower, group] of Object.entries(byVi)) {
  if (group.length <= 1) continue;
  const uniqueTrads = new Set(group.map((w) => w.traditional));
  if (uniqueTrads.size <= 1) {
    // Same traditional character appearing multiple times (e.g. different POS or level)
    // Distinguish by POS or English first gloss if helpful
    continue;
  }

  for (const w of group) {
    const hv = (w.hanViet || '').trim().toLowerCase();
    const curVi = (w.vietnamese || '').trim();
    const curViLower = curVi.toLowerCase();

    // If 2+ characters and hanViet is meaningful and not already identical to curViLower
    if (w.traditional.length >= 2 && hv && hv !== curViLower && !curViLower.includes(hv)) {
      w.vietnamese = `${curVi}, ${hv}`;
      disambiguatedCount++;
    } else if (w.traditional.length === 1 && hv && hv !== curViLower && !curViLower.includes(hv)) {
      // Single character word in a duplicate group: append Hán Việt in parentheses so it's distinct
      w.vietnamese = `${curVi} (${hv})`;
      disambiguatedCount++;
    }
  }
}

