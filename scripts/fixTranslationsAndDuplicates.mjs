function fixHanViet(w) {
  if (!w.hanViet) return '';
  const chars = Array.from(w.traditional || '');
  const syllables = w.hanViet.trim().split(/\s+/);
  const py = (w.pinyin || '').toLowerCase();

  if (chars.length === syllables.length) {
    for (let i = 0; i < chars.length; i++) {
      const ch = chars[i];
      if (CHAR_HV_MAP[ch]) {
        syllables[i] = CHAR_HV_MAP[ch];
      } else if (ch === '行') {
        // háng -> hàng/ngành, xíng -> hành
        if (py.includes('háng') || py.includes('hang') || ['銀行', '行業', '內行', '外行', '同行', '排行', '行列'].includes(w.traditional)) {
          syllables[i] = 'hàng';
        } else {
          syllables[i] = 'hành';
        }
      } else if (ch === '重') {
        if (py.includes('chóng') || py.includes('chong') || ['重複', '重新', '重疊', '雙重', '多重'].includes(w.traditional)) {
          syllables[i] = 'trùng';
        } else {
          syllables[i] = 'trọng';
        }
      } else if (ch === '長') {
        if (py.includes('zhǎng') || py.includes('ită') || py.includes('zhang') || ['成長', '生長', '長大', '長輩', '校長', '市長', '部長', '院長', '會長', '董事長', '家長', '班長', '組長', '科長', '處長', '局長', '廳長', '首長', '擅長', '專長', '長子', '長女'].includes(w.traditional)) {
          syllables[i] = 'trưởng';
        } else {
          syllables[i] = 'trường';
        }
      } else if (ch === '覺') {
        if (py.includes('jiào') || py.includes('jiao') || w.traditional === '睡覺') {
          syllables[i] = 'giáo';
        } else {
          syllables[i] = 'giác';
        }
      } else if (ch === '樂') {
        if (py.includes('yuè') || py.includes('yue') || ['音樂', '樂器', '樂團', '樂曲', '樂隊', '樂譜'].includes(w.traditional)) {
          syllables[i] = 'nhạc';
        } else {
          syllables[i] = 'lạc';
        }
      } else if (ch === '便') {
        if (py.includes('pián') || w.traditional === '便宜') {
          syllables[i] = 'tiện';
        } else {
          syllables[i] = 'tiện';
        }
      } else if (ch === '傳') {
        if (py.includes('zhuàn') || ['自傳', '傳記'].includes(w.traditional)) {
          syllables[i] = 'truyện';
        } else {
          syllables[i] = 'truyền';
        }
      } else if (ch === '調') {
        if (py.includes('diào') || ['強調', '調查', '聲調', '音調', '色調', '步調', '調動', '格調', '單調', '曲調'].includes(w.traditional)) {
          syllables[i] = 'điệu';
        } else {
          syllables[i] = 'điều';
        }
      }
    }
    return syllables.join(' ');
  }
  return w.hanViet;
}

